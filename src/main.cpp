// custom print function because of formatting problems in the default library
void printOLED(const char* text) { 
  display.clearDisplay();
  uint8_t size = computeMaxTextSize(text);
  display.setTextSize(size);
  display.setTextColor(SSD1306_WHITE);

  int16_t cursorX = 0;
  int16_t cursorY = 0;

  const int16_t screenW = display.width();
  const int16_t lineHeight = 8 * size;  // default font is 8px high at size 1

  const char* ptr = text;

  while (*ptr) {
    // skip leading spaces
    while (*ptr == ' ') {
      ptr++;
    }
    if (*ptr == '\0') break;

    // extract one word into a small buffer
    char word[64];
    int wi = 0;
    while (*ptr != ' ' && *ptr != '\0' && wi < (int)sizeof(word) - 1) {
      word[wi++] = *ptr++;
    }
    word[wi] = '\0';

    // measure how wide this word would be
    int16_t x1, y1;
    uint16_t w, h;
    display.getTextBounds(word, cursorX, cursorY, &x1, &y1, &w, &h);

    if (cursorX == 0 && w > screenW){
      display.setCursor(cursorX, cursorY);
      display.setTextWrap(true);
      display.print(word);
      display.print(' ');
      display.setTextWrap(false);
      cursorX = display.getCursorX();
      cursorY = display.getCursorY();
      continue;
    } else if (cursorX != 0 && (cursorX + (int16_t)w > screenW)) {
      cursorX = 0;
      cursorY += lineHeight;
      // stop if we run off the bottom of the screen
      if (cursorY + lineHeight > display.height()) break;
    }
    // Print the word
    display.setCursor(cursorX, cursorY);
    display.print(word);
    cursorX += w;
    

    // add a space after the word
    if (*ptr == ' ') {
      int16_t sx1, sy1;
      uint16_t sw, sh;
      display.getTextBounds(" ", cursorX, cursorY, &sx1, &sy1, &sw, &sh);
      cursorX += sw;
    }
  }

  display.display();
}


